"""Focused date-helper checks; integration cases live in test_xls_formats.py.

Grammar: https://support.microsoft.com/en-US/Excel/review-guidelines-for-customizing-a-number-format
Expected values are literal, not generated by the production helper.
"""
from decimal import Inexact, ROUND_UP, localcontext

import pytest

from legacy_office_parser._xls_dates import DateResult, MAX_ELAPSED_DAYS, interpret_date


@pytest.mark.parametrize('serial,mode,expected', [
    (0, 0, '1899-12-31'), (59, 0, '1900-02-28'), (61, 0, '1900-03-01'),
    (0, 1, '1904-01-01'), (60, 1, '1904-03-01'),
    (2958465, 0, '9999-12-31'), (2957003, 1, '9999-12-31'),
])
def test_calendar_boundaries(serial, mode, expected):
    assert interpret_date(serial, 14, mode) == DateResult('ok', (expected, 'date', expected))


@pytest.mark.parametrize('code,mode,expected', [
    (17, 0, '1900-03-01T12:00:00'), (22, 1, '1904-03-02T12:00:00'),
    (45, 0, '12:00:00'), (47, 0, '12:00:00'), (20, 1, '12:00:00'),
])
def test_representative_builtin_categories(code, mode, expected):
    assert interpret_date(61.5, code, mode) == DateResult('ok', (expected, 'date', expected))


@pytest.mark.parametrize('code', [
    'hh:mm mmm', 'mm:s', '"Today: "yyyy-mm-dd" at "hh:mm',
    r'yyyy\y-mm\m-dd\d', 'yyyy-mm-dd";[h]0"',
    '[Red][$-0409]yyyy-mm-dd', '[$-419]dd.mm.yyyy',
])
def test_calendar_recognition_ignores_literals_and_locale(code):
    expected = '2023-03-15T12:00:00'
    assert interpret_date(45000.5, code, 0) == DateResult('ok', (expected, 'date', expected))


@pytest.mark.parametrize('code', [
    'h:mm a/p', 'h" hours "mm" minutes "ss" seconds"',
    '"yyyy month"hh:mm', r'\d hh:mm', 'hh:mm:ss.000', '[$-409]hh:mm:ss',
])
def test_time_only_exempts_serial_60_and_ignores_literal_calendar_fields(code):
    assert interpret_date(60.5, code, 0) == DateResult('ok', ('12:00:00', 'date', '12:00:00'))


def test_normalized_time_keeps_milliseconds_regardless_of_mask():
    value = 61 + 1.23456 / 86400
    assert interpret_date(value, 'hh:mm', 0).result == ('00:00:01.234', 'date', '00:00:01.234')
    assert interpret_date(value, 14, 0).result == (
        '1900-03-01T00:00:01.234', 'date', '1900-03-01T00:00:01.234')


@pytest.mark.parametrize('code,value,mode,expected', [
    (46, 2, 0, '48:00:00'), (46, 60.5, 1, '1452:00:00'),
    ('[hh]:mm:ss', 0, 0, '00:00:00'), ('[mm]:ss', 1.5, 0, '2160:00'),
    ('[ss].00', .000016, 0, '01.38'),
    ('[h]:mm:ss.00', 1.99999999, 0, '48:00:00.00'),
    ('[h]" hours "mm" minutes"', 1.5, 0, '36 hours 00 minutes'),
    ('[h]', 1.9, 0, '45'), ('[h]:mm', 1.9999, 0, '47:59'),
    ('[m]', 1.9999, 0, '2879'), ('[h]:mm:ss', 1.999999, 0, '48:00:00'),
    ('[s]', MAX_ELAPSED_DAYS, 0, '255611376000'),
])
def test_elapsed_preserves_serial_and_renders_duration(code, value, mode, expected):
    assert interpret_date(value, code, mode) == DateResult('ok', (value, 'number', expected))


@pytest.mark.parametrize('code', [
    '"yyyy-mm-dd"', 'yyyy-mm-dd;hh:mm', '[>=0]yyyy-mm-dd',
    'yyyy-mm-dd0', 'yyyy-mm-dd"', 'yyyy-mm-dd\\', 'hhh',
    '[h]:mm:ss.0000', 'ss.0.0', 'hh:mm.00', '[h] yyyy', '[h] AM/PM',
    '[m]:hh', '[h]:[m]', '[$USD-409]yyyy', '[$-F800]yyyy',
    '[$-10409]yyyy', '[$-409][$-409]yyyy', '[$-999]yyyy',
    'yyyy' + ' ' * 61, 27,
])
def test_unsupported_masks_preserve_raw(code):
    outcome = interpret_date(61.5, code, 0)
    assert outcome.status == 'unsupported'
    assert outcome.reason
    assert outcome.result == (61.5, 'number', '61.5')


@pytest.mark.parametrize('value,code,mode,status', [
    (60.999, 'yyyy-mm-dd', 0, 'unrepresentable'),
    (-1, 14, 0, 'unrepresentable'), (-1, '[h]:mm:ss', 1, 'unrepresentable'),
    (2958466, 14, 0, 'out_of_range'), (2957004, 14, 1, 'out_of_range'),
    (1e200, 'hh:mm', 0, 'out_of_range'),
    (MAX_ELAPSED_DAYS + 1, '[s]', 0, 'out_of_range'),
    (1, 14, 2, 'unsupported'), (float('inf'), 14, 0, 'out_of_range'),
])
def test_distinct_fallback_statuses(value, code, mode, status):
    outcome = interpret_date(value, code, mode)
    assert outcome.status == status
    assert outcome.result == (value, 'number', str(value))
    assert outcome.reason


def test_elapsed_is_independent_of_ambient_decimal_context():
    with localcontext() as context:
        context.prec = 2
        context.rounding = ROUND_UP
        context.traps[Inexact] = True
        assert interpret_date(1.99999999, '[h]:mm:ss.00', 0).result == (
            1.99999999, 'number', '48:00:00.00')
        assert context.prec == 2
